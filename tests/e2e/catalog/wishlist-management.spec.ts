// ─── J-04/J-05/J-06/J-08/J-09/J-10: Add / View / Remove Lifecycle ──────────────

test.describe.serial('Wishlist Management — Add to Wishlist @regression', () => {
  test.beforeAll(async ({ browser }) => {
    // Guarantee a clean starting state regardless of leftovers from a prior run
    // (e.g. a previous failed attempt whose own cleanup didn't get to run) — this
    // is what caused TC-012 to see count (2) instead of (1) in an earlier run.
    const context = await browser.newContext({ storageState: 'tests/.auth/customer.json' });
    const page = await context.newPage();
    await new WishlistPage(page).removeAllItemsFromWishlist();
    await context.close();
  });

  test.afterEach(async ({ page }) => {
    // Safety-net cleanup: always leave the shared account empty for the next test.
    await new WishlistPage(page).removeAllItemsFromWishlist();
  });

  test('TC-012: Clicking the wishlist button on a product card adds it with a success message @REQ-05', async ({ page }) => {
    const wishlistPage = new WishlistPage(page);
    await wishlistPage.addProductToWishlistFromGridCard('cream', REFERENCE_PRODUCT_SLUG);
    await expect(await wishlistPage.getNotificationText()).toContain('The product has been added to your wishlist');
    await wishlistPage.assertHeaderWishlistCount(1);
  });

  test('TC-013: Clicking the wishlist button on the product detail page adds it with a success message @REQ-05', async ({ page }) => {
    const wishlistPage = new WishlistPage(page);
    await wishlistPage.addProductToWishlistFromPDP(REFERENCE_PRODUCT_SLUG);
    await expect(await wishlistPage.getNotificationText()).toContain('The product has been added to your wishlist');
    await wishlistPage.assertHeaderWishlistCount(1);
  });

  test('TC-005: Wishlist page displays a product card with item details and a remove action @REQ-03', async ({ page }) => {
    const wishlistPage = new WishlistPage(page);
    await wishlistPage.addProductToWishlistFromPDP(REFERENCE_PRODUCT_SLUG);
    await wishlistPage.navigate();
    await wishlistPage.dismissModals();
    await wishlistPage.assertItemsDisplayed(1);
    await expect(wishlistPage.wishlistItemCards.first()).toContainText('Cream');
    await expect(wishlistPage.wishlistItemCards.first()).toContainText('$33.00');
    await expect(wishlistPage.removeItemButtons.first()).toBeVisible();
  });

  test('TC-006: Wishlist page displays one card per saved product for multiple items @REQ-03', async ({ page }) => {
    const wishlistPage = new WishlistPage(page);
    await wishlistPage.addProductToWishlistFromPDP(REFERENCE_PRODUCT_SLUG);
    await wishlistPage.addProductToWishlistFromPDP(SECONDARY_PRODUCT_SLUG);
    await wishlistPage.navigate();
    await wishlistPage.dismissModals();
    await wishlistPage.assertItemsDisplayed(2);
  });

  test('TC-017: Header wishlist count increments by 1 immediately after adding a new product @REQ-06', async ({ page }) => {
    const wishlistPage = new WishlistPage(page);
    await wishlistPage.navigate();
    await wishlistPage.assertHeaderWishlistCount(0);
    await wishlistPage.addProductToWishlistFromPDP(REFERENCE_PRODUCT_SLUG);
    await wishlistPage.assertHeaderWishlistCount(1);
  });

  test('TC-018: Header wishlist count decrements by 1 immediately after removing an item @REQ-06', async ({ page }) => {
    const wishlistPage = new WishlistPage(page);
    await wishlistPage.addProductToWishlistFromPDP(REFERENCE_PRODUCT_SLUG);
    await wishlistPage.assertHeaderWishlistCount(1);
    await wishlistPage.navigate();
    await wishlistPage.dismissModals();
    await wishlistPage.dismissModals(); // re-check immediately before click — see TC-009 note in wishlist.page.ts
    await wishlistPage.removeItemButtons.first().click({ force: true });
    await wishlistPage.assertHeaderWishlistCount(0);
  });

  test('TC-015: Rapid double-click on "Add to wishlist" does not create a duplicate entry @REQ-05', async ({ page }) => {
    const wishlistPage = new WishlistPage(page);
    await page.goto(REFERENCE_PRODUCT_SLUG);
    await wishlistPage.dismissModals();
    await expect(wishlistPage.pdpWishlistButton).toBeVisible({ timeout: 10000 });
    // Re-dismiss immediately before clicking — see the identical note in
    // addProductToWishlistFromPDP: the auto-opening overlay can silently
    // reappear between the dismiss above and this click and absorb it.
    await wishlistPage.dismissModals();
    await Promise.all([
      wishlistPage.pdpWishlistButton.click({ force: true }),
      wishlistPage.pdpWishlistButton.click({ force: true }),
    ]);
    // Let the AJAX call(s) actually settle before navigating away — navigating too early
    // races the in-flight request and makes the wishlist page load before the add lands.
    await waitForAjaxComplete(page);
    await wishlistPage.navigate();
    await wishlistPage.dismissModals();
    await wishlistPage.assertItemsDisplayed(1);
  });

  test('TC-016: Add-to-wishlist AJAX request returns 200 and reflects in the DOM without a full page reload @REQ-05', async ({ page }) => {
    const wishlistPage = new WishlistPage(page);
    await page.goto(REFERENCE_PRODUCT_SLUG);
    await wishlistPage.dismissModals();
    await wishlistPage.dismissModals();
    const [response] = await Promise.all([
      page.waitForResponse((res) => res.url().includes('/addproducttocart/details/') && res.request().method() === 'POST'),
      wishlistPage.pdpWishlistButton.click({ force: true }),
    ]);
    expect(response.status()).toBe(200);
    await wishlistPage.assertHeaderWishlistCount(1);
  });

  test('TC-014: Re-adding an already-wishlisted product repeats the success message and increments the header count, but does not duplicate the grid entry @REQ-05', async ({ page }) => {
    const wishlistPage = new WishlistPage(page);
    await wishlistPage.addProductToWishlistFromPDP(REFERENCE_PRODUCT_SLUG);
    await wishlistPage.assertHeaderWishlistCount(1);

    // Re-add the SAME product — see memory/decisions.md D-011 for the confirmed, escalated discrepancy.
    await page.goto(REFERENCE_PRODUCT_SLUG);
    await wishlistPage.dismissModals();
    await wishlistPage.dismissModals();
    const [reAddResponse] = await Promise.all([
      page.waitForResponse((res) => res.url().includes('/addproducttocart/details/') && res.request().method() === 'POST'),
      wishlistPage.pdpWishlistButton.click({ force: true }),
    ]);
    expect(reAddResponse.status()).toBe(200);
    await expect(await wishlistPage.getNotificationText()).toContain('The product has been added to your wishlist');

    // Header count over-increments (D-011) ...
    await wishlistPage.assertHeaderWishlistCount(2);
    // ... but the grid stays deduplicated to exactly 1 card. Do NOT assert these two
    // numbers are equal — that is precisely the confirmed discrepancy under test here.
    await wishlistPage.navigate();
    await wishlistPage.dismissModals();
    await wishlistPage.assertItemsDisplayed(1);
  });
});

// ─── J-11: Large Wishlist (20+ Items) Boundary ─────────────────────────────────

test.describe.serial('Wishlist Management — Large Wishlist Boundary @regression', () => {
  const TWENTY_PLUS_SLUGS = [
    '/cream', '/gel-cream', '/eye-cream', '/eye-gel-cream', '/body-cream', '/hand-cream',
    '/toner-3', '/toner-pad',
    '/lip-mask', '/hair-mask', '/sheet-mask-2', '/wash-off-mask-2', '/clay-mask', '/mud-mask',
    '/serum', '/serum-mist', '/eye-serum', '/lip-serum', '/sun-serum', '/hair-serum',
    '/special-set',
  ];

  test.beforeAll(async ({ browser }) => {
    const context = await browser.newContext({ storageState: 'tests/.auth/customer.json' });
    const page = await context.newPage();
    await new WishlistPage(page).removeAllItemsFromWishlist();
    await context.close();
  });

  test.afterEach(async ({ page }) => {
    await new WishlistPage(page).removeAllItemsFromWishlist();
  });

  test('TC-009: Wishlist with a large number of items (20+) renders without breaking layout @REQ-03', async ({ page }) => {
    // 21 sequential navigate+add+ajax-wait cycles against a live site (~8-10s each,
    // observed) plus a 21-item afterEach cleanup — 120s measurably wasn't enough
    // (a real run timed out with only 16-18/21 items added). Budgeted generously.
    test.setTimeout(400_000);
    const wishlistPage = new WishlistPage(page);
    for (const slug of TWENTY_PLUS_SLUGS) {
      await wishlistPage.addProductToWishlistFromPDP(slug);
    }
    await wishlistPage.navigate();
    await wishlistPage.dismissModals();
    // The grid initially renders only 20 items (infinite-scroll pagination,
    // confirmed live — memory/decisions.md D-012) — load the rest before asserting.
    await wishlistPage.loadAllWishlistItems();
    await wishlistPage.assertItemsDisplayed(TWENTY_PLUS_SLUGS.length);
  });
});


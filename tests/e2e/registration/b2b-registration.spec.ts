/** Open a fresh admin-authenticated page reusing tests/.auth/admin.json (no re-login). */
async function withAdminPage<T>(browser: Browser, fn: (page: Page) => Promise<T>): Promise<T> {
  const context = await browser.newContext({ storageState: 'tests/.auth/admin.json' });
  const page = await context.newPage();
  try {
    return await fn(page);
  } finally {
    await context.close();
  }
}

/** Register a full account and wait for the result page. Returns the data used. */
async function registerFullAccount(page: Page, overrides: Partial<B2BRegistrationData> = {}): Promise<B2BRegistrationData> {
  const registerPage = new RegisterPage(page);
  const data = generateDynamicB2BRegistrationData(overrides);
  await registerPage.navigate();
  await registerPage.registerB2BUser(data);
  await registerPage.assertRegistrationSubmitted();
  return data;
}

test.describe('B2B Registration — Core Lifecycle @regression', () => {
  test('TC-001: Successful B2B registration creates inactive account, mapped to ERP application @REQ-01', async ({ page, browser }) => {
    const data = await registerFullAccount(page);

    await withAdminPage(browser, async (adminPage) => {
      const customerDetails = new AdminCustomerDetailsPage(adminPage);
      await customerDetails.searchOnly(data.email);
      await customerDetails.assertRoleContains(data.email, 'B2B Customer');

      const applications = new AdminRegistrationApplicationsPage(adminPage);
      await applications.navigate();
      await applications.assertGridDisplayed();
      await applications.assertApplicationDataVisible(data.companyName, { company: data.companyName });
    });
  });

  test('TC-002: Valid submission with alternate Type of Business and Contact Media combination @REQ-01', async ({ page }) => {
    await registerFullAccount(page, {
      typeOfBusiness: 'Retailer (Physical shop only)',
      preferredContactChannel: 'Messenger',
      messengerAccountName: `msgr_${generateRandomString(6)}`,
      messengerAccountLink: 'https://m.me/test-account',
      whatsAppNumber: undefined,
    });
  });

  test('TC-003: Missing required field (Company Name) blocks submission — no entity created @REQ-01', async ({ page, browser }) => {
    const registerPage = new RegisterPage(page);
    const data = generateDynamicB2BRegistrationData({ companyName: '' });
    await registerPage.navigate();
    await registerPage.fillStep1(data);
    const advanced = await registerPage.goToNextStep();
    expect(advanced).toBe(false);
    await registerPage.assertValidationError('company name is required');

    await withAdminPage(browser, async (adminPage) => {
      const customerDetails = new AdminCustomerDetailsPage(adminPage);
      const rowCount = await customerDetails.getMatchingRowCount(data.email);
      expect(rowCount).toBe(0);
    });
  });

  test('TC-004: Rapid double-click on Submit does not create duplicate entities @REQ-01', async ({ page, browser }) => {
    const registerPage = new RegisterPage(page);
    const data = generateDynamicB2BRegistrationData();
    await registerPage.navigate();
    await registerPage.fillCompleteB2BRegistrationForm(data);

    // Fire two rapid clicks synchronously — a real double-click race, not two sequential Playwright actions.
    await page.evaluate(() => {
      const btn = document.querySelector('#kd-register-submit') as HTMLButtonElement | null;
      btn?.click();
      btn?.click();
    });
    await registerPage.assertRegistrationSubmitted();

    await withAdminPage(browser, async (adminPage) => {
      const customerDetails = new AdminCustomerDetailsPage(adminPage);
      const rowCount = await customerDetails.getMatchingRowCount(data.email);
      expect(rowCount).toBe(1);
    });
  });
});


test.describe('B2B Registration — Admin Activation Lifecycle @smoke @regression', () => {
  test('TC-028: Admin activates account via Active flag + save — login enabled @REQ-08', async ({ page, browser }) => {
    const data = await registerFullAccount(page);

    await withAdminPage(browser, async (adminPage) => {
      const customerDetails = new AdminCustomerDetailsPage(adminPage);
      await customerDetails.searchAndOpenCustomer(data.email);
      await customerDetails.assertCustomerEditPageDisplayed();
      await customerDetails.approveAndActivateAccount();
      await customerDetails.assertSaveSuccess();
      await customerDetails.assertAccountIsActive();
    });

    const loginContext = await browser.newContext();
    const loginPage = new LoginPage(await loginContext.newPage());
    await loginPage.navigate();
    await loginPage.login(data.email, data.password);
    await expect(loginPage.page).not.toHaveURL(/\/login/, { timeout: 15000 });
    await loginContext.close();
  });

  test('TC-029: Login attempt before admin approval is blocked with inactive-account message @REQ-08', async ({ page }) => {
    const data = await registerFullAccount(page);

    const loginPage = new LoginPage(page);
    await loginPage.navigate();
    await loginPage.login(data.email, data.password);
    await expect(loginPage.page.locator('body')).toContainText(/account is not active/i, { timeout: 10000 });
    await expect(loginPage.page).toHaveURL(/\/login/);
  });

  test('TC-030: Admin deactivates a previously-active account — login blocked again @REQ-08', async ({ page, browser }) => {
    const data = await registerFullAccount(page);

    await withAdminPage(browser, async (adminPage) => {
      const customerDetails = new AdminCustomerDetailsPage(adminPage);
      await customerDetails.searchAndOpenCustomer(data.email);
      await customerDetails.approveAndActivateAccount();
      await customerDetails.assertAccountIsActive();

      await customerDetails.deactivateAccount();
      await customerDetails.assertAccountIsInactive();
    });

    const loginContext = await browser.newContext();
    const loginPage = new LoginPage(await loginContext.newPage());
    await loginPage.navigate();
    await loginPage.login(data.email, data.password);
    await expect(loginPage.page.locator('body')).toContainText(/account is not active/i, { timeout: 10000 });
    await loginContext.close();
  });
});
